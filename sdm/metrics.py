"""FFT-based ADC metrics: SNDR, ENOB, SFDR, THD.

Method (IEEE 1241-style, windowed rather than coherent):
* 4-term Blackman-Harris window (sidelobes < -92 dB), so the test tone does not
  need to land exactly on an FFT bin. That matters on the board, where the tone is
  generated by a PWM, not by a lab generator.
* Power is computed per bin with the window's power normalisation, so summing the
  bins of a sine of amplitude A gives A**2 / 2, and summing noise bins gives
  the noise power in that bandwidth.
* Signal = the tone's main lobe (+/- SIG_HALF bins). Noise + distortion = every
  other in-band bin except the DC bins.
"""
from __future__ import annotations

import numpy as np
from scipy.signal import windows

FS_SINE_POWER = 0.5     # power of a full-scale sine (amplitude 1) in normalised units
SIG_HALF = 6            # bins on each side of the tone counted as signal (BH4 main lobe = +/-4)
DC_BINS = 6             # bins 0..DC_BINS-1 are excluded (offset and window leakage)


def _bh(n: int) -> np.ndarray:
    return windows.blackmanharris(n, sym=False)


def power_bins(v, fs: float):
    """One-sided power per bin (normalised units^2) and the bin frequencies."""
    v = np.asarray(v, dtype=float)
    n = len(v)
    w = _bh(n)
    X = np.fft.rfft(v * w)
    P = 2.0 * np.abs(X) ** 2 / (n * np.sum(w ** 2))
    P[0] /= 2.0
    f = np.fft.rfftfreq(n, 1.0 / fs)
    return f, P


def spectrum_dbfs(v, fs: float, navg: int = 1):
    """Amplitude spectrum in dBFS for plotting: a full-scale sine peaks at 0 dBFS.

    ``navg`` > 1 splits the record into that many segments and averages their
    power (Welch, no overlap), which smooths the noise floor so the noise-shaping
    slope is readable. Metrics always use the full record (``analyze_tone``).

    Returns (f, dbfs, nbw_hz). The noise floor level depends on the noise
    bandwidth per bin (nbw_hz), so it is reported alongside each plot.
    """
    v = np.asarray(v, dtype=float)
    n = len(v) // navg
    w = _bh(n)
    segs = (v[:n * navg] - v.mean()).reshape(navg, n)
    p = np.mean(np.abs(np.fft.rfft(segs * w, axis=1)) ** 2, axis=0)
    amp = 2.0 * np.sqrt(p) / np.sum(w)
    f = np.fft.rfftfreq(n, 1.0 / fs)
    nbw = fs * np.sum(w ** 2) / np.sum(w) ** 2
    return f, 20.0 * np.log10(amp + 1e-15), nbw


def analyze_tone(v, fs: float, f_band: float, f_sig: float | None = None,
                 n_harm: int = 7) -> dict:
    """SNDR / ENOB / SFDR / THD of a single-tone record ``v`` within [0, f_band]."""
    f, P = power_bins(v, fs)
    n = len(np.asarray(v))
    kb = min(int(np.floor(f_band / fs * n)), len(P) - 1)

    if f_sig is None:
        k0 = DC_BINS + int(np.argmax(P[DC_BINS:kb + 1]))
    else:
        kg = int(round(f_sig / fs * n))
        lo, hi = max(kg - 3, DC_BINS), min(kg + 4, kb + 1)
        k0 = lo + int(np.argmax(P[lo:hi]))
    sig = np.arange(max(k0 - SIG_HALF, 0), min(k0 + SIG_HALF + 1, len(P)))
    p_sig = P[sig].sum()
    # interpolated tone frequency (power-weighted centroid of the main lobe)
    f0 = float(np.sum(f[sig] * P[sig]) / p_sig)

    mask = np.zeros(len(P), dtype=bool)
    mask[DC_BINS:kb + 1] = True
    mask[sig] = False
    p_noise = P[mask].sum() * (kb + 1) / mask.sum()   # extrapolate over excluded bins

    # harmonics (folded about fs/2), each counted over the same main-lobe width
    p_harm = 0.0
    for h in range(2, n_harm + 1):
        fh = (h * f0) % fs
        if fh > fs / 2:
            fh = fs - fh
        kh = int(round(fh / fs * n))
        if DC_BINS + SIG_HALF <= kh <= kb - SIG_HALF and abs(kh - k0) > 2 * SIG_HALF:
            p_harm += P[kh - SIG_HALF:kh + SIG_HALF + 1].sum()

    # largest spur: main-lobe-wide rolling power outside the signal and DC bins
    Pn = np.where(mask, P, 0.0)
    roll = np.convolve(Pn, np.ones(2 * SIG_HALF + 1), mode="same")
    roll[~mask] = 0.0
    p_spur = roll.max() if roll.max() > 0 else 1e-30

    sndr = 10 * np.log10(p_sig / p_noise)
    return {
        "f_sig_hz": f0,
        "sig_dbfs": 10 * np.log10(p_sig / FS_SINE_POWER),
        "sndr_db": sndr,
        "enob_bits": (sndr - 1.76) / 6.02,
        "sfdr_db": 10 * np.log10(p_sig / p_spur),
        "thd_db": 10 * np.log10(p_harm / p_sig) if p_harm > 0 else float("-inf"),
        "noise_dbfs": 10 * np.log10(p_noise / FS_SINE_POWER),
        "n_fft": n,
        "f_band_hz": f_band,
    }


def theory_sqnr_db(order: int, osr: float, bits: int = 1) -> float:
    """Textbook peak SQNR of an L-th order modulator with a full-scale sine input
    (linear white-noise model): 6.02N + 1.76 - 10log(pi^2L/(2L+1)) + (2L+1)10log(OSR)."""
    L = order
    return (6.02 * bits + 1.76
            - 10 * np.log10(np.pi ** (2 * L) / (2 * L + 1))
            + (2 * L + 1) * 10 * np.log10(osr))
